#!/usr/bin/env bash
# Render Formula/ctfkit.rb for a release of compliancetf/ctfkit.
#
# Usage: scripts/update-formula.sh [tag]
#
# With no tag it takes the latest release that is not a pre-release. It reads
# the release's checksums.txt and, unless SKIP_ATTESTATION=1, checks the build
# provenance of every archive with `gh attestation verify` first, so the formula
# never pins an archive the ctfkit release workflow did not build.
set -euo pipefail

repo=compliancetf/ctfkit
tag=${1:-$(gh api "repos/${repo}/releases/latest" --jq .tag_name)}
if ! [[ $tag =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
	echo "update-formula: ${tag} is not a release version vMAJOR.MINOR.PATCH" >&2
	exit 2
fi
version=${tag#v}
base="https://github.com/${repo}/releases/download/${tag}"

tmp=$(mktemp -d "${TMPDIR:-/tmp}/update-formula.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
curl -fsSL --proto '=https' --tlsv1.2 --retry 2 --max-time 60 -o "${tmp}/checksums.txt" "${base}/checksums.txt"

sum() {
	local name="ctfkit_${version}_$1.tar.gz" s
	s=$(awk -v n="$name" '$2 == n { print $1 }' "${tmp}/checksums.txt")
	if ! [[ $s =~ ^[0-9a-f]{64}$ ]]; then
		echo "update-formula: ${name} is not in checksums.txt of ${tag}" >&2
		exit 1
	fi
	if [ "${SKIP_ATTESTATION:-0}" != 1 ]; then
		curl -fsSL --proto '=https' --tlsv1.2 --retry 2 --max-time 120 -o "${tmp}/${name}" "${base}/${name}"
		(cd "$tmp" && echo "${s}  ${name}" | shasum -a 256 -c - > /dev/null)
		gh attestation verify "${tmp}/${name}" -R "$repo" \
			--signer-workflow "${repo}/.github/workflows/release.yml" \
			--source-ref "refs/tags/${tag}" --deny-self-hosted-runners > /dev/null
	fi
	echo "$s"
}

darwin_arm64=$(sum Darwin_arm64)
darwin_amd64=$(sum Darwin_x86_64)
linux_arm64=$(sum Linux_arm64)
linux_amd64=$(sum Linux_x86_64)

cat > Formula/ctfkit.rb <<RUBY
# Generated by scripts/update-formula.sh from the ${tag} release of ${repo}.
class Ctfkit < Formula
  desc "Run the same Terraform and OpenTofu checks across your pipelines"
  homepage "https://github.com/${repo}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/ctfkit_${version}_Darwin_arm64.tar.gz"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}/ctfkit_${version}_Darwin_x86_64.tar.gz"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/ctfkit_${version}_Linux_arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/ctfkit_${version}_Linux_x86_64.tar.gz"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "ctfkit"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ctfkit version")
  end
end
RUBY
echo "Formula/ctfkit.rb: ${tag}"
